"""What a clarification actually buys, instead of what we assume it buys.

THE HOLE THIS CLOSES. `findings.md` §23 names it the largest one in the arm comparison: "No user
simulator, so a clarification is priced at half an episode and abandonment is unmeasurable. This
flatters B and C and penalises D and E." Every arm that buys safety by asking rather than
answering is scored against a constant nobody measured. The break-even curve multiplies exactly
that constant, so it cannot rest on an assumption.

So: when a run ends in `clarify`, answer it the way the asker would have, ask again, and record
what came back. The clarify column stops being one bucket and becomes three.

    resolved_correct    asking worked. One round trip bought a right answer.
    resolved_wrong      asking cost a round trip and the answer is still wrong.
    unresolved          it clarified again, or refused. The round trip bought nothing.

WHAT THE SIMULATED ASKER SAYS is derived from the case, never invented, and never generated by a
model. A model-written reply would add a second source of variance to the thing being measured,
and the run-to-run spread is already the reason this module exists. It says what a person says
when asked which definition they meant: the owner, what it is used for, and the governed name.

WHICH READING IT ASKS FOR is the FIRST declared candidate, by convention, and the convention is
stated here rather than left to authoring order. On a genuinely contested question neither reading
is "the" intended one — that is what makes it contested — so the choice is arbitrary and must be
consistent. What is being measured is not which reading the asker wanted; it is whether the agent,
once TOLD, answers correctly for the reading it was given.

IT IS A RE-ASK, NOT A CONTINUATION, and that is a property of the agent rather than a shortcut
here. The engine has no memory by design: every question is a fresh conversation, which removes
conversational state as a rival explanation for any result. A second turn is therefore the
original question with the ambiguity resolved in words, which is also what a real user does when
a system asks them to be more specific.

WHAT IT COSTS IS RECORDED SEPARATELY. The row's own telemetry stays the first turn's, and the
second turn carries its own tokens, cost and latency under `second_turn`. Folding them together
would make "what the first attempt cost" unrecoverable, and the two are different questions: one
prices the attempt, the pair prices the episode.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass

from .grade import grade_numeric

__all__ = ["Reply", "reply_for", "follow_up"]

# Resolutions, in the vocabulary the utility model consumes.
RESOLVED_CORRECT = "resolved_correct"
RESOLVED_WRONG = "resolved_wrong"
UNRESOLVED = "unresolved"

_DEFAULT_TOLERANCE = 0.005


@dataclass(frozen=True)
class Reply:
    """What the asker says, and the number that then answers them."""

    text: str
    metric: str
    value: float | None
    tolerance: float


def reply_for(case: dict) -> Reply | None:
    """The asker's answer to a clarifying question, or None when the case has no reading to name.

    Pure, so the wording is testable without a model and reviewable without a run. Returns None
    for a non-contested case and for a contested one whose first candidate has no resolved value:
    an oracle that did not resolve cannot grade an answer, and inventing a target would make the
    second turn score against a number nobody computed.
    """
    expect = case.get("expect") or {}
    if expect.get("type") != "contested":
        return None
    candidates = expect.get("candidates") or ()
    if not candidates:
        return None
    first = candidates[0]
    value = first.get("value")           # resolved onto the candidate by gold.compute_gold
    if value is None:
        return None
    # What a person says: whose definition, what it is for, and its governed name. Every part is
    # read off the case, so a reply cannot drift from the reading it is supposed to select.
    text = (f"I mean the one owned by {first['owner']}, the definition used for "
            f"{first['consumer']} — {first['metric']}.")
    return Reply(text=text, metric=first["metric"], value=float(value),
                 tolerance=float(expect.get("tolerance") or _DEFAULT_TOLERANCE))


def follow_up(answer, case: dict, run_one: Callable[[str], object]) -> dict | None:
    """Answer the agent's clarification and ask again. None when there is nothing to follow up.

    `run_one` takes the re-asked question and returns an `Answer`. The module owns WHEN to follow
    up, WHAT to say and HOW to score it; the caller owns only execution, so a runner cannot get
    the policy subtly different from another runner's.

    Only a `clarify` is followed up. A refusal is a visible decline the reader can act on, and an
    answer already ended the episode; re-asking either would price a round trip nobody spent.
    """
    if getattr(answer, "outcome", None) != "clarify":
        return None
    reply = reply_for(case)
    if reply is None:
        return None

    asked = f"{case['question']} {reply.text}"
    second = run_one(asked)

    if second.outcome != "answer":
        resolution = UNRESOLVED
        correct = False
    else:
        # Graded against the CHOSEN candidate's own oracle, not the case's gold — a contested case
        # has no single gold, and that is the fact the case exists to state.
        served = second.declared_value
        text = str(served) if served is not None else second.answer
        correct = bool(grade_numeric(text, reply.value, reply.tolerance)["correct"])
        resolution = RESOLVED_CORRECT if correct else RESOLVED_WRONG

    return {
        "asked": asked,
        "wanted_metric": reply.metric,
        "wanted_value": reply.value,
        "resolution": resolution,
        "correct": correct,
        "outcome": second.outcome,
        "answer": second.answer,
        "declared_value": second.declared_value,
        "source_metric": second.source_metric,
        "reason": second.reason,
        "error": second.error,
        # Its own meter. The first turn's cost stays on the row; the episode is the sum, and a
        # caller that wants one or the other can have it.
        "input_tokens": second.input_tokens,
        "output_tokens": second.output_tokens,
        "cached_tokens": second.cached_tokens,
        "model_calls": second.model_calls,
        "tool_calls": second.tool_calls,
    }
