#!/usr/bin/env python3
"""Variants of the governed layer that change ONE thing about how the contested pair is presented.

THE QUESTION THIS ANSWERS. On the shipped layer the agent served `active_users` 35 times out of 35
and never mentioned `active_accounts`. Two properties of the presentation could be doing that work
and the baseline cannot tell them apart:

    the NAME     the question says "active users" and one metric is called `active_users`
    the ORDER    that metric is also the first one in the catalogue

So: rename both so neither matches the question's wording, and separately flip the order. If the
behaviour is unchanged in both, the presentation is not the cause and no prompt will fix it.

WHY GENERATED RATHER THAN COPIED. A variant is the base layer plus a stated transformation, and
three hand-maintained copies of one file drift the moment the base changes. The transformation is
the treatment, so it is written here as data and applied; the output carries a header saying it is
generated. Comments do not survive the round trip, which is why the base file keeps them and these
do not.

WHAT DOES NOT CHANGE. The case file names its candidates by the metric name on the SHIPPED layer,
and the oracles run against the raw tables, so neither moves with a variant. Grading attributes a
served figure by its VALUE rather than by the name the model declared — decided when the grader was
written, for a different reason — which is exactly what lets one case score every variant.

    python variants.py --write      # materialise variants/<name>/
    python variants.py --list       # what each one changes
"""
from __future__ import annotations

import argparse
import pathlib

import yaml

HERE = pathlib.Path(__file__).resolve().parent
BASE = HERE / "layer"
OUT = HERE / "variants"

_HEADER = ("# GENERATED by variants.py from ../../layer/. Do not edit — edit the base layer and\n"
           "# re-run `python variants.py --write`.\n#\n# {what}\n")

# name -> (what it changes, {old metric name: new}, whether to put the contested pair in reverse
# declaration order). The empty variant is the control and is written out too, so all three arms
# are read from the same place and no arm is "the one that skips the generator".
# The contested pair on the BASE layer, by the names it ships with. Held here so the transformations
# below can find it after a rename, and so adding a variant never means updating a list of every
# name any variant has ever used.
PAIR = ("active_users", "active_accounts")   # (excludes internal = 886, includes = 919)

VARIANTS: dict[str, tuple[str, dict[str, str], bool]] = {
    "baseline": (
        "The shipped layer, unchanged. `active_users` matches the question's wording exactly and "
        "is declared first.",
        {}, False),
    "no_exact_match": (
        "`active_users` renamed to `active_customers`, so NEITHER metric matches the question's "
        "wording. Everything else is identical: same measures, same filters, same numbers, same "
        "order. The only variable is whether one candidate wears the question's own words.",
        {"active_users": "active_customers"}, False),
    "reversed": (
        "The same names, with the contested pair declared in the opposite order, so "
        "`active_accounts` is the first of the two the catalogue lists. Tests position rather "
        "than wording — and if the served number changes, the answer depended on the order of a "
        "list.",
        {}, True),
    "crossed": (
        "The two cues put in OPPOSITION, which no other variant does. `active_accounts` (which "
        "INCLUDES internal and test accounts, 919) becomes `active_customers`, so the question's "
        "own word now sits on the reading the agent has never chosen; `active_users` (which "
        "EXCLUDES them, 886) becomes `real_customers`, where only the meaning of `real` points. "
        "Every earlier variant left both cues on the same metric, so none of them could separate "
        "wording from reasoning. Serving 886 says the agent reads the descriptions; serving 919 "
        "says the question's wording was doing the work.",
        {"active_users": "real_customers", "active_accounts": "active_customers"}, False),
}


def _docs() -> list[dict]:
    return [d for d in yaml.safe_load_all((BASE / "semantic_models.yml").read_text()) if d]


def _apply(docs: list[dict], renames: dict[str, str], reverse: bool) -> list[dict]:
    out = []
    for doc in docs:
        if "metric" in doc:
            m = dict(doc["metric"])
            m["name"] = renames.get(m["name"], m["name"])
            out.append({"metric": m})
        else:
            out.append(doc)
    if reverse:
        # Swap the two contested metrics where they sit, rather than reversing the whole file: the
        # treatment is the order of the PAIR, and moving every other metric too would confound it.
        pair = [i for i, d in enumerate(docs)
                if "metric" in d and d["metric"]["name"] in PAIR]
        if len(pair) == 2:
            i, j = pair
            out[i], out[j] = out[j], out[i]
    return out


def write(name: str) -> pathlib.Path:
    what, renames, reverse = VARIANTS[name]
    directory = OUT / name
    directory.mkdir(parents=True, exist_ok=True)
    body = "---\n".join(yaml.safe_dump(d, sort_keys=False, width=100)
                        for d in _apply(_docs(), renames, reverse))
    (directory / "semantic_models.yml").write_text(_HEADER.format(what=what) + "---\n" + body)
    (directory / "project.yaml").write_text((BASE / "project.yaml").read_text())
    return directory


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()
    for name, (what, renames, reverse) in VARIANTS.items():
        print(f"{name:16} {what}")
        if args.list:
            print(f"{'':16} renames={renames or '-'}  reversed={reverse}")
        if args.write:
            print(f"{'':16} -> {write(name)}")


if __name__ == "__main__":
    main()
